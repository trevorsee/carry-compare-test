export default function GuidePage({ params }: { params: { slug: string } }) {
  const guide = guides[params.slug];

  if (!guide) {
    notFound();
  }

  return (
    <div className="container mx-auto px-4 py-8 max-w-4xl">
      <div className="mb-6">
        <Link href="/guides" className="text-blue-600 hover:underline">
          ← Back to Guides
        </Link>
      </div>

      <h1 className="text-4xl font-bold mb-6">{guide.title}</h1>

      <div className="prose max-w-none">
        {guide.content.split('\n').map((line, i) => {
          if (line.startsWith('# ')) {
            return <h1 key={i} className="text-3xl font-bold mt-8 mb-4">{line.slice(2)}</h1>;
          }
          if (line.startsWith('## ')) {
            return <h2 key={i} className="text-2xl font-semibold mt-6 mb-3">{line.slice(3)}</h2>;
          }
          if (line.startsWith('### ')) {
            return <h3 key={i} className="text-xl font-semibold mt-4 mb-2">{line.slice(4)}</h3>;
          }
          if (line.startsWith('- [ ]')) {
            return (
              <div key={i} className="flex items-start mb-2">
                <input type="checkbox" className="mr-2 mt-1" disabled />
                <span>{line.slice(6)}</span>
              </div>
            );
          }
          if (line.startsWith('- ')) {
            return <li key={i} className="ml-6 mb-1">{line.slice(2)}</li>;
          }
          if (line.trim() === '') {
            return <br key={i} />;
          }
          if (line.includes('[') && line.includes('](')) {
            const match = line.match(/\[([^\]]+)\]\(([^)]+)\)/);
            if (match) {
              return (
                <p key={i} className="mb-4">
                  <Link href={match[2]} className="text-blue-600 hover:underline">
                    {match[1]}
                  </Link>
                </p>
              );
            }
          }
          return <p key={i} className="mb-4 text-gray-700">{line}</p>;
        })}
      </div>

      <div className="mt-8">
        <Link href="/compare" className="text-blue-600 hover:underline">
          Compare Plans →
        </Link>
      </div>
    </div>
  );
}
